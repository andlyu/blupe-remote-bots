#!/usr/bin/env python3
"""Bundle controller URDF kinematics and original I2RT STL visuals for Path Studio.

The controller's URDF is kinematics-only. Its companion MJCF defines the STL
visual origins; the existing vendored I2RT linear_4310 supplies the real gripper.
No runtime Python packages, network access, or robot connections are needed.
"""
import base64
import hashlib
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "models/controller-yam"


def numbers(value, default):
    return [float(v) for v in (value or default).split()]


def rpy_quaternion(rpy):
    r, p, y = [v / 2 for v in rpy]
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return [cr*cp*cy+sr*sp*sy, sr*cp*cy-cr*sp*sy, cr*sp*cy+sr*cp*sy, cr*cp*sy-sr*sp*cy]


def main():
    urdf = ET.parse(SOURCE / "yam.urdf").getroot()
    frames = []
    for i in range(1, 7):
        joint = urdf.find(f"joint[@name='joint{i}']")
        origin, limit = joint.find("origin"), joint.find("limit")
        axis = numbers(joint.find("axis").get("xyz"), "0 0 1")
        assert axis[:2] == [0, 0] and abs(axis[2]) == 1
        frames.append(dict(p=numbers(origin.get("xyz"), "0 0 0"), q=rpy_quaternion(numbers(origin.get("rpy"), "0 0 0")), limit=[float(limit.get("lower")), float(limit.get("upper"))], sign=axis[2]))
    origin = urdf.find("joint[@name='fixed_grasp']/origin")
    tool = dict(p=numbers(origin.get("xyz"), "0 0 0"), q=rpy_quaternion(numbers(origin.get("rpy"), "0 0 0")))
    meshes, visuals, hashes = {}, [], {}

    def include_mesh(name, path):
        data = path.read_bytes()
        meshes[name] = base64.b64encode(data).decode("ascii")
        hashes[str(path.relative_to(ROOT))] = hashlib.sha256(data).hexdigest()

    mjcf = ET.parse(SOURCE / "yam.xml").getroot()
    for mesh in mjcf.findall("./asset/mesh"):
        include_mesh(mesh.get("name"), ROOT / "models/yam/assets" / mesh.get("file"))
    # MJCF visual origins are in each link's post-joint frame, not at joint centres.
    for parent in [mjcf.find("worldbody"), *mjcf.findall(".//body")]:
        frame = parent.get("name", "base_link")
        for geom in parent.findall("geom"):
            if geom.get("type") != "mesh":
                continue
            visuals.append(dict(frame=frame, mesh=geom.get("mesh"), transforms=[dict(p=numbers(geom.get("pos"), "0 0 0"), q=numbers(geom.get("quat"), "1 0 0 0"))]))

    gripper_dir = ROOT / "aspire/assets/linear_4310"
    grip = ET.parse(gripper_dir / "linear_4310.xml").getroot()
    for mesh in grip.findall("./asset/mesh"):
        include_mesh("linear_" + mesh.get("name"), gripper_dir / "assets" / mesh.get("file"))
    body = grip.find("./worldbody/body")
    for child in [body, *body.findall("body")]:
        chain = []
        slide = None
        if child is not body:
            chain.append(dict(p=numbers(child.get("pos"), "0 0 0"), q=numbers(child.get("quat"), "1 0 0 0")))
            joint = child.find("joint")
            axis = numbers(joint.get("axis"), "0 0 1")
            slide = dict(transform_index=len(chain), axis=axis, range=numbers(joint.get('range'), '0 0.0475'))
            chain.append(dict(p=[0, 0, 0], q=[1, 0, 0, 0]))
        for geom in child.findall("geom"):
            visuals.append(dict(frame="link6", mesh="linear_" + geom.get("mesh"), transforms=chain + [dict(p=numbers(geom.get("pos"), "0 0 0"), q=numbers(geom.get("quat"), "1 0 0 0"))], **(dict(slide=slide) if slide else {})))

    for path in [SOURCE / "yam.urdf", SOURCE / "yam_bimanual.urdf", SOURCE / "yam.xml", gripper_dir / "linear_4310.xml"]:
        hashes[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
    provenance = dict(controller_repository="andlyu/blupe-playground-robot-controller", controller_commit="d1f9e8d588b18810d13c0edbe34646763dc8f257", urdf="models/controller-yam/yam_bimanual.urdf", visual_origins="models/controller-yam/yam.xml", gripper="aspire/assets/linear_4310/linear_4310.xml", hashes=hashes, note="Controller URDF joint chain; companion MJCF visual origins; original STL meshes. User-specified station spacing overrides the generic URDF's 0.70 m layout.")
    model = dict(frames=frames, tool=tool, visuals=visuals, meshes=meshes, provenance=provenance)
    data = json.dumps(model, separators=(",", ":"))
    target = ROOT / "static/path-studio-yam-model.js"
    target.write_text("/* Generated by scripts/build_path_studio_model.py. I2RT assets: models/controller-yam/I2RT_LICENSE. */\n(function(root){const model=" + data + ";if(typeof module!=='undefined'&&module.exports)module.exports=model;root.PathStudioYamModel=model;})(typeof window==='undefined'?globalThis:window);\n")
    (SOURCE / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    print(f"Bundled {len(meshes)} original STL meshes, {len(visuals)} visual instances, and {len(frames)} URDF joints ({target.stat().st_size:,} bytes).")


if __name__ == "__main__":
    main()
